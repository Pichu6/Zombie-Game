"""Police per 100,000 by country (spec 69, data review part 2, research data-review-life DRL-4).

Rewrites the generated part of data/services/police.toml from a raw file outside the repo (RAW_DIR, default ../data_raw):
  police/unodc-police-per-100k-2026-10-13.csv   per country UNODC's police personnel (data_cts_access_and_functioning_
                                                of_justice.xlsx, 2026) over World Bank population, latest year 2004-2024
The [country] table holds every real profile (data/setup/nations/real/<ISO3>.toml) with a value; [group] holds the median
of each income group's profiles; the curve's reference_per_100k becomes UNODC's USA value, so the BJS curve (US sworn
officers by town size) is scaled by the ratio of two numbers from one source. Prints a summary.

usage: python tools/data/police.py [RAW_DIR]
"""
import csv
import pathlib
import re
import statistics
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
RAW = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "data_raw"
SRC = RAW / "police" / "unodc-police-per-100k-2026-10-13.csv"
OUT = ROOT / "data" / "services" / "police.toml"
BEGIN, END = "# BEGIN GENERATED by tools/data/police.py", "# END GENERATED"
GROUPS = ("high", "upper_middle", "lower_middle", "low")


def income_of(path):
    m = re.search(r'^\s*income\s*=\s*"([a-z_]+)"', path.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else None


def main():
    profiles = {p.stem: income_of(p) for p in (ROOT / "data" / "setup" / "nations" / "real").glob("*.toml")}
    rates = {}
    for r in csv.DictReader(SRC.open(encoding="utf-8")):
        if r["iso3"] in profiles and r["police_per_100k"]:
            rates[r["iso3"]] = (float(r["police_per_100k"]), r["year"])
    groups = {g: statistics.median(v for iso, (v, _) in rates.items() if profiles[iso] == g)
              for g in GROUPS if any(profiles[iso] == g for iso in rates)}
    usa = rates["USA"][0]
    block = [BEGIN,
             "# Police personnel per 100,000 people: UNODC head counts over World Bank population, each country's latest year",
             "# 2004-2024 (DRL-4); [group] is the median of the group's countries, for a country UNODC does not cover.",
             "[group]"]
    block += [f"{g} = {groups[g]:.1f}" for g in GROUPS if g in groups]
    block += ["", "[country]"]
    block += [f"{iso} = {v:.1f}   # {year}" for iso, (v, year) in sorted(rates.items())]
    block += [END]
    text = OUT.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + "\n".join(block) + text[text.index(END) + len(END):]
    else:  # the first run replaces the hand-written [country] table
        start = text.index("[country]")
        end = text.index("[station]")
        text = text[:start] + "\n".join(block) + "\n\n" + text[end:]
    text = re.sub(r"^reference_per_100k = .*$",
                  f"reference_per_100k = {usa:.1f}        # DRL-4: UNODC's USA police per 100,000, the curve's own country (was SV-21's 217 sworn)",
                  text, count=1, flags=re.M)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rates)} countries of {len(profiles)} profiles; reference USA {usa:.1f}; "
          + ", ".join(f"{g} {v:.0f}" for g, v in groups.items()))


if __name__ == "__main__":
    main()
