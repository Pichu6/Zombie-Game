"""Wages by country (spec 62, data review part 2, research data-review-life DL).

Writes data/employment/wages.toml from a raw file outside the repo (RAW_DIR, default ../data_raw):
  employment/ilostat-wages-2026-10-13.csv   per country the latest ILOSTAT mean earnings of employees (2016-2025, current
                                            USD; hourly DF_EAR_EHRA, monthly DF_EAR_EMTA, weekly hours DF_HOW_XEES), and
                                            per World Bank income group the median of its countries' hourly values with
                                            the ILO's modelled weekly hours (DF_HOW_TEMP); gathered 2026-10-13
A country with only a monthly figure gets hourly = monthly / (weekly hours x 52 / 12), with its own hours or its group's.
Rows marked low confidence are left out (the group's value is used). Only countries with a real profile
(data/setup/nations/real/<ISO3>.toml) get a table. Prints a summary.

usage: python tools/data/wages.py [RAW_DIR]
"""
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
RAW = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "data_raw"
SRC = RAW / "employment" / "ilostat-wages-2026-10-13.csv"
OUT = ROOT / "data" / "employment" / "wages.toml"
GROUPS = {"WLD_HIC": "high", "WLD_UMC": "upper_middle", "WLD_LMC": "lower_middle", "WLD_LIC": "low"}
WEEKS_PER_MONTH = 52.0 / 12.0


def main():
    profiles = {p.stem for p in (ROOT / "data" / "setup" / "nations" / "real").glob("*.toml")}
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    group_hours, group_hourly = {}, {}
    for r in rows:
        if r["iso3"] in GROUPS:
            g = GROUPS[r["iso3"]]
            group_hours[g] = float(r["weekly_hours"])
            group_hourly[g] = float(r["hourly_usd"])
    countries = {}
    for r in rows:
        iso = r["iso3"]
        if iso in GROUPS or iso not in profiles or r["confidence"] == "low":
            continue
        group = r["income_group"].replace("-", "_")
        hourly, how = None, ""
        if r["hourly_usd"]:
            hourly, how = float(r["hourly_usd"]), "hourly"
        elif r["monthly_usd"]:
            hours = float(r["weekly_hours"]) if r["weekly_hours"] else group_hours.get(group)
            if hours:
                hourly = float(r["monthly_usd"]) / (hours * WEEKS_PER_MONTH)
                how = "monthly / " + ("its hours" if r["weekly_hours"] else "group hours")
        if hourly is None or hourly <= 0:
            continue
        if iso in countries and countries[iso][2] == "hourly" and how != "hourly":
            continue  # keep the hourly series over a derived one
        if iso in countries and "ilo" not in r["source_url"].lower() and "ilo" in countries[iso][3].lower():
            continue  # keep ILOSTAT over a second source (one series for every country)
        countries[iso] = (hourly, r["year"], how, r["source_url"])
    lines = [
        "# What an hour of work pays (spec 62): cents per hour for a pop with a job, by country (ISO3, the real profile it",
        "# takes, spec 49) or by income group through [index]. GENERATED by tools/data/wages.py from ILOSTAT (data review part 2,",
        "# research data-review-life): mean earnings of employees in current US dollars, each country's latest year 2016-2025;",
        "# a monthly figure is divided by weekly hours x 52/12. Group tables are the median of their countries (2019 or later).",
        "# Employees only: the informal and self-employed majority of low-income countries is not in these figures.",
        "",
    ]
    for g in ("high", "upper_middle", "lower_middle", "low"):
        lines += [f"[{g}]", f"cents_per_hour = {round(group_hourly[g] * 100)}   # median of the group's countries; "
                            f"{group_hours[g]} h a week worked (ILO 2024)", ""]
    for iso in sorted(countries):
        hourly, year, how, _ = countries[iso]
        lines += [f"[{iso}]", f"cents_per_hour = {round(hourly * 100)}   # {year}, {how}", ""]
    lines += ["[index]            # which table an income group reads when its country has none",
              'high = "high"', 'upper_middle = "upper_middle"', 'lower_middle = "lower_middle"', 'low = "low"', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(countries)} countries of {len(profiles)} profiles; groups "
          + ", ".join(f"{g} {group_hourly[g]:.2f} USD/h" for g in group_hourly))
    for iso in ("USA", "GBR", "CHN", "IND", "BRA", "NGA", "MEX", "PAK"):
        if iso in countries:
            print(f"  {iso}: {countries[iso][0]:.2f} USD/h ({countries[iso][1]}, {countries[iso][2]})")


if __name__ == "__main__":
    main()
