"""Writes data/tier0/census.toml: the block's ~60 neighbours (spec 22).

Deterministic (fixed seed). Household sizes follow US ACS 2022 shares (1: 28 %, 2: 35 %, 3: 15 %,
4: 13 %, 5+: 9 %); ages from a simple adult/child split. Bodies are drawn later by the simulation
from each person's id, so this table only holds who they are and where they live.
The TOML file is the source of truth once written; rerun only to regenerate from scratch.
"""
import random

rng = random.Random(20261006)
first_m = ["Luis", "Carlos", "James", "Miguel", "David", "Jorge", "Robert", "Andres", "Tomas", "Peter",
           "Raul", "Samuel", "Victor", "Hector", "Daniel", "Frank", "Oscar", "Pablo", "Martin", "Ivan"]
first_f = ["Ana", "Maria", "Laura", "Sofia", "Elena", "Carmen", "Linda", "Patricia", "Rosa", "Julia",
           "Marta", "Grace", "Lucia", "Paula", "Irene", "Nora", "Claudia", "Teresa", "Alicia", "Diana"]
last = ["Ortega", "Ramirez", "Walsh", "Moreno", "Castillo", "Novak", "Herrera", "Kim", "Silva", "Brennan",
        "Rojas", "Medina", "Fischer", "Vargas", "Delgado", "Okafor", "Pereira", "Lindqvist", "Navarro", "Duarte"]
homes = ["house_a", "house_b"] + [f"street_{i}" for i in range(1, 40)]
sizes = [1, 2, 3, 4, 5]
weights = [28, 35, 15, 13, 9]

people = []
for hi, home in enumerate(homes):
    n = rng.choices(sizes, weights)[0]
    surname = last[hi % len(last)]
    for k in range(n):
        child = k >= 2 and rng.random() < 0.7
        sex = rng.choice(["m", "f"])
        age = rng.randint(4, 17) if child else rng.randint(19, 84)
        name = rng.choice(first_m if sex == "m" else first_f)
        while any(q[0] == f"{name} {surname}" for q in people):  # no two neighbours share a full name
            name = rng.choice(first_m if sex == "m" else first_f)
        people.append((f"{name} {surname}", age, sex, f"h{hi + 1}", home))
    if len(people) >= 60:
        break
people = people[:60]

with open("data/tier0/census.toml", "w") as f:
    f.write("# The block's neighbours (spec 22). Generated by tools/census/make_census.py; edit freely.\n")
    f.write("# home: house_a / house_b are on the map; street_N are off-map homes.\n")
    f.write("# survivor = true marks the found-survivor slots (spec 26), full pops later.\n\n")
    for i, (name, age, sex, hh, home) in enumerate(people):
        f.write(f'[[person]]\nname = "{name}"\nage = {age}\nsex = "{sex}"\nhousehold = "{hh}"\nhome = "{home}"\n')
        if i in (7, 23, 41):
            f.write("survivor = true\n")
        f.write("\n")
print(len(people), "people")
